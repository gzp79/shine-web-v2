import fs from 'node:fs';
import type { Plugin } from 'vite';

/**
 * Replaces `*.remote.ts` modules with generated stubs when building/serving Storybook.
 *
 * Remote functions need SvelteKit's own pipeline: the kit plugin rewrites `*.remote.ts` into client
 * proxies that pull in `$app/state` internals, and the resulting module only works inside a kit
 * build or dev server. Storybook's standalone vite build fails on it outright (the exports resolve
 * to nothing), and Storybook has no server to answer a remote call anyway.
 */

const VIRTUAL_PREFIX = '\0remote-stub:';
const REMOTE_FILE = /\.remote\.(ts|js)$/;
const REMOTE_EXPORT = /export\s+const\s+([A-Za-z_$][\w$]*)\s*=\s*(query|command|form|prerender)\b/g;

/** A query is called while a component renders, so it has to resolve to something shaped like one. */
const RUNTIME_HELPERS = `
const pendingQuery = () => {
    const promise = new Promise(() => {});
    return Object.assign(promise, {
        loading: true,
        current: undefined,
        error: undefined,
        refresh: async () => {},
        withOverride: () => promise
    });
};

const unavailable = (name) => () => {
    throw new Error(
        \`Remote function "\${name}" is not available in Storybook - wrap the component in a mock provider instead.\`
    );
};
`;

function buildStub(source: string, file: string): string {
    const exports = [...source.matchAll(REMOTE_EXPORT)].map(([, name, kind]) => ({ name, kind }));

    const lines = exports.map(({ name, kind }) =>
        kind === 'query' || kind === 'prerender'
            ? `export const ${name} = () => pendingQuery();`
            : `export const ${name} = unavailable('${name}');`
    );

    // A remote module with no recognised exports means the pattern above has drifted from the real
    // syntax; failing loudly beats silently serving an empty module.
    if (lines.length === 0) {
        throw new Error(`[remote-stub] found no remote exports in ${file} - has the export syntax changed?`);
    }

    return `// generated by .storybook/remote-stub.ts from ${file}\n${RUNTIME_HELPERS}\n${lines.join('\n')}\n`;
}

export function stubRemoteFunctions(): Plugin {
    return {
        name: 'storybook-stub-remote-functions',
        enforce: 'pre',

        async resolveId(source, importer, options) {
            if (source.startsWith(VIRTUAL_PREFIX)) return source;
            if (!importer) return null;

            const resolved = await this.resolve(source, importer, { ...options, skipSelf: true });
            if (!resolved || !REMOTE_FILE.test(resolved.id)) return null;

            // The path is encoded rather than appended: kit matches remote modules with
            // /[/.]remote\.[^/]+$/, so any id still containing `.remote.` gets rewritten by its own
            // plugin afterwards - which replaces this stub with an empty module.
            return VIRTUAL_PREFIX + Buffer.from(resolved.id).toString('base64url');
        },

        load(id) {
            if (!id.startsWith(VIRTUAL_PREFIX)) return null;

            const file = Buffer.from(id.slice(VIRTUAL_PREFIX.length), 'base64url').toString();
            return buildStub(fs.readFileSync(file, 'utf8'), file);
        }
    };
}
